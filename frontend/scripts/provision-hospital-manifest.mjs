import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const inputPath = process.argv[2];
if (!inputPath) throw new Error('Usage: npm run provision -- <hospital-manifest.json>');

const manifest = JSON.parse(readFileSync(resolve(inputPath), 'utf8').replace(/^\uFEFF/, ''));
if (
  manifest?.version !== 1 || typeof manifest.keyId !== 'string' || !manifest.keyId.trim() ||
  typeof manifest.encryptionPublicKey !== 'string' || typeof manifest.signingPublicKey !== 'string' ||
  typeof manifest.createdAt !== 'number' || !Number.isFinite(manifest.createdAt)
) throw new Error('Hospital manifest has an invalid structure.');

const decodePublicKey = (label, value) => {
  const normalized = value.trim();
  // The native libsodium 'base64' output is URLSAFE_NO_PADDING. Accept either
  // alphabet at import, validate canonical bytes, then store the runtime format.
  if (!/^(?:[A-Za-z0-9_-]{43}|[A-Za-z0-9+/]{43})=?$/.test(normalized)) {
    throw new Error(`${label} must be a 32-byte Base64 or Base64URL public key.`);
  }
  const standard = normalized.replace(/-/g, '+').replace(/_/g, '/').replace(/=+$/, '');
  const bytes = Buffer.from(standard, 'base64');
  if (bytes.length !== 32 || bytes.toString('base64').replace(/=+$/, '') !== standard) {
    throw new Error(`${label} must contain exactly 32 bytes with canonical Base64 encoding.`);
  }
  return bytes.toString('base64url');
};

// Whitelist public fields so a mistakenly supplied identity cannot embed secrets.
const publicManifest = {
  version: manifest.version,
  keyId: manifest.keyId,
  encryptionPublicKey: decodePublicKey('Hospital encryption public key', manifest.encryptionPublicKey),
  signingPublicKey: decodePublicKey('Hospital signing public key', manifest.signingPublicKey),
  createdAt: manifest.createdAt,
};

const outputPath = resolve('src/core/security/hospitalManifest.ts');
const serialized = JSON.stringify(publicManifest, null, 2);
const contents = `import { HospitalPublicManifest } from '../../../../backend/src/protocol/hospitalManifest';\n\n// Generated by npm run provision. This file contains public keys only.\nexport const HOSPITAL_PUBLIC_MANIFEST: HospitalPublicManifest = ${serialized};\n`;
writeFileSync(outputPath, contents, 'utf8');
console.log(`Provisioned Civilian build for Hospital key ID: ${manifest.keyId}`);
