import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const inputPath = process.argv[2];
if (!inputPath) throw new Error('Usage: npm run provision -- <hospital-manifest.json>');

const manifest = JSON.parse(readFileSync(resolve(inputPath), 'utf8'));
if (
  manifest?.version !== 1 || typeof manifest.keyId !== 'string' || !manifest.keyId.trim() ||
  typeof manifest.encryptionPublicKey !== 'string' || typeof manifest.signingPublicKey !== 'string' ||
  typeof manifest.createdAt !== 'number' || !Number.isFinite(manifest.createdAt)
) throw new Error('Hospital manifest has an invalid structure.');

const decodePublicKey = (label, value) => {
  const normalized = value.replace(/\s/g, '');
  if (!/^[A-Za-z0-9+/]+={0,2}$/.test(normalized)) throw new Error(`${label} is not valid base64.`);
  const bytes = Buffer.from(normalized, 'base64');
  if (bytes.length !== 32 || bytes.toString('base64').replace(/=+$/, '') !== normalized.replace(/=+$/, '')) throw new Error(`${label} must contain exactly 32 bytes.`);
};

decodePublicKey('Hospital encryption public key', manifest.encryptionPublicKey);
decodePublicKey('Hospital signing public key', manifest.signingPublicKey);

const outputPath = resolve('src/core/security/hospitalManifest.ts');
const serialized = JSON.stringify(manifest, null, 2);
const contents = `import { HospitalPublicManifest } from '../../../../backend/src/protocol/hospitalManifest';\n\n// Generated by npm run provision. This file contains public keys only.\nexport const HOSPITAL_PUBLIC_MANIFEST: HospitalPublicManifest = ${serialized};\n`;
writeFileSync(outputPath, contents, 'utf8');
console.log(`Provisioned Civilian build for Hospital key ID: ${manifest.keyId}`);
